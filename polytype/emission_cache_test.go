package main

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

// Each invocation runs in a fresh process. Nothing but the disk cache survives.
func TestEmissionCacheProcess(t *testing.T) {
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	cache := t.TempDir()
	write := func(name, content string) {
		t.Helper()
		p := filepath.Join(dir, name)
		if e := os.MkdirAll(filepath.Dir(p), 0755); e != nil {
			t.Fatal(e)
		}
		if e := os.WriteFile(p, []byte(content), 0644); e != nil {
			t.Fatal(e)
		}
	}
	gomod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	write("go.mod", strings.Replace(string(gomod), "module github.com/tylergannon/polytype", "module example.com/cachefixture", 1)+"\nrequire github.com/tylergannon/polytype v0.0.0\nreplace github.com/tylergannon/polytype => "+root+"\n")
	sum, err := os.ReadFile(filepath.Join(root, "go.sum"))
	if err != nil {
		t.Fatal(err)
	}
	write("go.sum", string(sum))
	write("types.go", "package fixture\n// Person belongs in the generated docs.\ntype Person struct { Name string `json:\"name\"` }\n")
	write("schema.go", "//go:build jsonschema\n\npackage fixture\nimport (\"encoding/json\"; p \"github.com/tylergannon/polytype\")\nfunc (Person) Schema() json.RawMessage {panic(\"stub\")}\nvar _ = p.Declare(Person.Schema)\n")
	run := func(want string, success bool, extra ...string) time.Duration {
		t.Helper()
		cmd := exec.Command(cli, "--target", dir, "--typescript", filepath.Join(dir, "ts"), "--pretty")
		cmd.Env = append(os.Environ(), "POLYTYPE_CACHE_DIR="+cache, "POLYTYPE_CACHE_TRACE=1", "GOMAXPROCS=2")
		cmd.Env = append(cmd.Env, extra...)
		for _, setting := range extra {
			if cwd, ok := strings.CutPrefix(setting, "POLYTYPE_TEST_CWD="); ok {
				cmd.Dir = cwd
			}
		}
		start := time.Now()
		out, e := cmd.CombinedOutput()
		elapsed := time.Since(start)
		t.Logf("%s wall=%s output=%s", want, elapsed, out)
		if want == "hit" && bytes.Contains(out, []byte("polytype cache: load ")) {
			t.Fatalf("cache hit performed semantic package loading: %s", out)
		}
		if (e == nil) != success || !bytes.Contains(out, []byte(want)) {
			t.Fatalf("want success=%v %q: error=%v output=%s", success, want, e, out)
		}
		return elapsed
	}
	run("stored", true)
	before, err := os.ReadFile(filepath.Join(dir, "ts/types.ts"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(before, []byte(`"name": string`)) || !bytes.Contains(before, []byte("Person belongs in the generated docs.")) {
		t.Fatalf("missing independently supplied fields/comment: %s", before)
	}
	run("hit", true, "UNRELATED_SESSION_ID=different", "PWD=/not-the-working-directory", "_=unrelated-command")
	run("hit", true, "POLYTYPE_TEST_CWD="+dir)
	write("types_test.go", "package fixture\nfunc testOnlyHelper() string { return \"first\" }\n")
	run("hit", true)
	write("types_test.go", "package fixture\nfunc testOnlyHelper() string { return \"changed\" }\n")
	run("hit", true)
	run("bypass", true, "POLYTYPE_CACHE=off")
	run("hit", true)
	goBefore, err := os.ReadFile(filepath.Join(dir, "jsonschema_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	damage := func() {
		write("jsonschema_gen.go", "// Code generated by polytype. DO NOT EDIT.\n\nthis is broken Go\n")
		write("jsonschema/Person.json", "broken schema")
		write("ts/types.ts", "// Code generated by polytype. DO NOT EDIT.\n broken TS")
	}
	assertRepaired := func() {
		t.Helper()
		b, e := os.ReadFile(filepath.Join(dir, "jsonschema_gen.go"))
		if e != nil || !bytes.Equal(b, goBefore) {
			t.Fatalf("generated Go repair: %v %s", e, b)
		}
		ts, e := os.ReadFile(filepath.Join(dir, "ts/types.ts"))
		if e != nil || !bytes.Equal(ts, before) {
			t.Fatalf("TypeScript repair: %v %s", e, ts)
		}
		schema, e := os.ReadFile(filepath.Join(dir, "jsonschema/Person.json"))
		if e != nil || !bytes.Contains(schema, []byte(`"name"`)) {
			t.Fatalf("schema repair: %v %s", e, schema)
		}
	}
	damage()
	run("hit", true)
	assertRepaired()
	damage()
	run("bypass", true, "POLYTYPE_CACHE=off")
	assertRepaired()
	write("generated_test.go", `package fixture
import("encoding/json";"testing")
func TestGeneratedSchema(t *testing.T){
 var schema struct{Properties map[string]struct{Type string}}
 if err:=json.Unmarshal((Person{}).Schema(),&schema);err!=nil{t.Fatal(err)}
 if schema.Properties["name"].Type!="string"{t.Fatalf("name schema = %#v",schema.Properties)}
}
`)
	prove := exec.Command("go", "test", "-run", "^TestGeneratedSchema$", "-count=1", "-v", ".")
	prove.Dir = dir
	if out, e := prove.CombinedOutput(); e != nil || !bytes.Contains(out, []byte("--- PASS: TestGeneratedSchema")) {
		t.Fatalf("generated accessor runtime: %v %s", e, out)
	}

	if err = os.Remove(filepath.Join(dir, "jsonschema_gen.go")); err != nil {
		t.Fatal(err)
	}
	if err = os.RemoveAll(filepath.Join(dir, "jsonschema")); err != nil {
		t.Fatal(err)
	}
	if err = os.RemoveAll(filepath.Join(dir, "ts")); err != nil {
		t.Fatal(err)
	}
	run("hit", true)
	after, err := os.ReadFile(filepath.Join(dir, "ts/types.ts"))
	if err != nil || !bytes.Equal(before, after) {
		t.Fatalf("recovery: %v\n%s", err, after)
	}
	schema, err := os.ReadFile(filepath.Join(dir, "jsonschema/Person.json"))
	if err != nil || !bytes.Contains(schema, []byte(`"name"`)) {
		t.Fatalf("schema recovery: %v %s", err, schema)
	}
	write("types.go", "package fixture\n// Person has a changed field.\ntype Person struct { Age int `json:\"age\"` }\n")
	run("stored", true)
	after, err = os.ReadFile(filepath.Join(dir, "ts/types.ts"))
	if err != nil || !bytes.Contains(after, []byte(`"age": number`)) || bytes.Contains(after, []byte(`"name": string`)) {
		t.Fatalf("source freshness: %v %s", err, after)
	}
	run("hit", true)
	// Cross-package source participates even when the consumer's own file is unchanged.
	write("dep/types.go", "package dep\n// Detail comes from a dependency.\ntype Detail struct { Score int `json:\"score\"` }\n")
	write("types.go", "package fixture\nimport \"example.com/cachefixture/dep\"\ntype Person struct { Detail dep.Detail `json:\"detail\"` }\n")
	run("stored", true)
	assertTS := func(want string) {
		t.Helper()
		b, e := os.ReadFile(filepath.Join(dir, "ts/types.ts"))
		if e != nil || !bytes.Contains(b, []byte(want)) {
			t.Fatalf("want %q: %v %s", want, e, b)
		}
	}
	assertTS(`"score": number`)
	write("dep/types.go", "package dep\n// Detail changed without editing the root.\ntype Detail struct { Label string `json:\"label\"` }\n")
	run("stored", true)
	assertTS(`"label": string`)
	assertTS("Detail changed without editing the root.")
	// Build-excluded production files are conservatively included because
	// codec collision checks inspect them, outside jsonschema selection.
	write("dep/production.go", "//go:build !jsonschema\n\npackage dep\nfunc (Detail) MarshalJSON() ([]byte,error) { return nil,nil }\n")
	run("stored", true)
	if err = os.Remove(filepath.Join(dir, "dep/production.go")); err != nil {
		t.Fatal(err)
	}
	run("stored", true)
	// Adding/deleting a production file cannot reuse a prior valid result.
	write("dep/extra.go", "package dep\ntype Added string\n")
	run("stored", true)
	if err = os.Remove(filepath.Join(dir, "dep/extra.go")); err != nil {
		t.Fatal(err)
	}
	run("stored", true)
	run("hit", true)

	// Hits still run output ownership checks.
	write("ts/types.ts", "// handwritten application file\n")
	run("refusing to overwrite unowned TypeScript output", false)
	// Corruption and an unwritable location fall back to ordinary generation.
	if err = os.Remove(filepath.Join(dir, "ts/types.ts")); err != nil {
		t.Fatal(err)
	}
	entries, err := filepath.Glob(filepath.Join(cache, "polytype-emission-v1", "*.json"))
	if err != nil || len(entries) != 1 {
		t.Fatalf("source revisions must replace one target slot: %v %v", entries, err)
	}
	for _, entry := range entries {
		if err = os.WriteFile(entry, []byte("{broken"), 0600); err != nil {
			t.Fatal(err)
		}
	}
	run("stored", true)
	write("no-cache-dir", "file")
	run("miss", true, "POLYTYPE_CACHE_DIR="+filepath.Join(dir, "no-cache-dir"))
}
