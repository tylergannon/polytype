// Package javascript projects the validated Go type grammar into a JavaScript
// ES module of JSDoc type declarations.
//
// The input is a validated [github.com/tylergannon/polytype/typegrammar]
// definition graph, as produced by github.com/tylergannon/polytype/grammar or
// by the CLI's own lowering. The output is a single types.js module declaring
// one exported JSDoc typedef per definition. The declarations are type-only:
// the module carries no runtime decoder, validator, or value export, and
// consumers import the types with `import('./types.js').Name` under
// allowJs/checkJs.
//
// This is an independent projection over typegrammar, not a transpilation of
// the TypeScript backend's types.ts. It covers the same wire shapes and shares
// the TypeScript backend's identifier allocation and header conventions so a
// caller can rely on [Result.Names] matching.
//
// Emitted typedef names are collision-safe and may differ from the Go type
// name, so a caller writing its own references reads them from [Result.Names]
// rather than assuming the Go name.
package javascript

import (
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/constant"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/tylergannon/polytype/typegrammar"
)

// GeneratedHeader identifies files owned by this generator. It matches the
// TypeScript backend's header so both outputs are recognizable as generated.
const GeneratedHeader = "// Code generated by polytype. DO NOT EDIT.\n"

// Options is reserved for future output choices. There is deliberately no
// barrel: a JSDoc typedef is not a runtime binding, so an ES module cannot
// re-export it, and an `export {}` barrel would contain nothing. Every
// declaration is emitted in types.js.
type Options struct{}

// File is one generated output, named relative to whatever directory the
// caller writes it to.
type File struct {
	Name    string
	Content []byte
}

// Result is the output of one Generate call.
type Result struct {
	// Files holds types.js.
	Files []File
	// Names maps every definition to the typedef identifier it was emitted
	// under. The identifier is the Go type name unless that name is not a
	// legal JavaScript identifier, is reserved, or is claimed by a definition
	// of the same name in another package.
	Names map[typegrammar.Name]string
}

// Generate validates defs and renders all declarations before returning any
// files. It never mutates defs and returns nothing on error.
func Generate(defs typegrammar.Definitions, _ Options) (Result, error) {
	if err := defs.Validate(); err != nil {
		return Result{}, fmt.Errorf("generate JavaScript: %w", err)
	}

	names := allocateNames(defs)
	typedefs := make([]typedef, 0, len(defs))
	for _, def := range defs {
		body, err := projector{names: names}.project(def.Type, def.Name.String())
		if err != nil {
			return Result{}, err
		}
		typedefs = append(typedefs, typedef{
			name:        names[def.Name],
			description: def.Description,
			body:        body,
		})
	}

	files := []File{{Name: "types.js", Content: printModule(typedefs)}}
	return Result{Files: files, Names: names}, nil
}

type projector struct {
	names map[typegrammar.Name]string
}

func (p projector) project(t typegrammar.Type, at string) (typeExpr, error) {
	switch n := t.(type) {
	case *typegrammar.Scalar:
		switch n.Kind {
		case typegrammar.Bool:
			return keywordType("boolean"), nil
		case typegrammar.String:
			return keywordType("string"), nil
		default:
			return keywordType("number"), nil
		}
	case *typegrammar.Time:
		return keywordType("string"), nil
	case *typegrammar.Enum:
		members := make([]typeExpr, 0, len(n.Members))
		for _, member := range n.Members {
			var literal string
			if n.Mode == typegrammar.EnumNames {
				literal = quote(member.Name)
			} else if n.Kind == typegrammar.String {
				literal = quote(constant.StringVal(member.Value))
			} else {
				var err error
				literal, err = numericLiteral(member.Value)
				if err != nil {
					return nil, fmt.Errorf("generate JavaScript: %s enum member %s: %w", at, member.Name, err)
				}
			}
			members = append(members, literalType(literal))
		}
		return union(members...), nil
	case *typegrammar.Object:
		if len(n.Fields) == 0 {
			return keywordType("object"), nil
		}
		properties := make([]property, 0, len(n.Fields))
		for _, field := range n.Fields {
			typ, optional, err := p.projectField(field.Value, at+"."+field.GoName)
			if err != nil {
				return nil, err
			}
			properties = append(properties, property{
				name:        field.JSONName,
				description: field.Description,
				optional:    optional,
				typeExpr:    typ,
			})
		}
		return objectType{properties: properties}, nil
	case *typegrammar.Pointer:
		return p.project(n.Element, at+".pointer")
	case *typegrammar.Slice:
		element, err := p.project(n.Element, at+".items")
		if err != nil {
			return nil, err
		}
		return genericType{name: "Array", arguments: []typeExpr{element}}, nil
	case *typegrammar.Array:
		element, err := p.project(n.Element, at+".items")
		if err != nil {
			return nil, err
		}
		return genericType{name: "Array", arguments: []typeExpr{element}}, nil
	case *typegrammar.Ref:
		return referenceType(p.names[n.Target]), nil
	default:
		return nil, fmt.Errorf("generate JavaScript: %s: unsupported type constructor %T", at, t)
	}
}

func (p projector) projectField(value typegrammar.FieldValue, at string) (typeExpr, bool, error) {
	switch n := value.(type) {
	case *typegrammar.Required:
		typ, err := p.project(n.Type, at)
		return typ, false, err
	case *typegrammar.Optional:
		typ, err := p.project(n.Type, at)
		return typ, true, err
	case *typegrammar.Nullable:
		typ, err := p.project(n.Type, at)
		return union(typ, keywordType("null")), false, err
	case *typegrammar.Union:
		typ, err := p.projectUnion(*n, at)
		return typ, false, err
	case *typegrammar.OptionalUnion:
		typ, err := p.projectUnion(n.Union, at)
		return typ, true, err
	case *typegrammar.UnionSlice:
		typ, err := p.projectUnion(n.Union, at)
		if err != nil {
			return nil, false, err
		}
		return genericType{name: "Array", arguments: []typeExpr{typ}}, false, nil
	case *typegrammar.Provided:
		return nil, false, fmt.Errorf("generate JavaScript: %s: the field's schema is provided outside the type grammar and has no static type", at)
	default:
		return nil, false, fmt.Errorf("generate JavaScript: %s: unsupported field constructor %T", at, value)
	}
}

func (p projector) projectUnion(u typegrammar.Union, at string) (typeExpr, error) {
	variants := make([]typeExpr, 0, len(u.Variants))
	for _, variant := range u.Variants {
		name, ok := p.names[variant.Implementation]
		if !ok {
			return nil, fmt.Errorf("generate JavaScript: %s: unresolved union implementation %s", at, variant.Implementation)
		}
		payload := genericType{
			name: "Omit",
			arguments: []typeExpr{
				referenceType(name),
				literalType(quote(u.Discriminator)),
			},
		}
		discriminator := objectType{properties: []property{{
			name:     u.Discriminator,
			typeExpr: literalType(quote(variant.Tag)),
		}}}
		variants = append(variants, intersection(payload, discriminator))
	}
	return union(variants...), nil
}

func numericLiteral(value constant.Value) (string, error) {
	_, exact := constant.Float64Val(constant.ToFloat(value))
	if !exact {
		return "", fmt.Errorf("integer %s is not exactly representable as a JavaScript number", value.ExactString())
	}
	return value.ExactString(), nil
}

func quote(value string) string {
	encoded, _ := json.Marshal(value)
	return string(encoded)
}

func allocateNames(defs typegrammar.Definitions) map[typegrammar.Name]string {
	bases := make(map[typegrammar.Name]string, len(defs))
	counts := make(map[string]int, len(defs))
	for _, def := range defs {
		base := safeIdentifier(def.Name.Name)
		if reservedWords[base] {
			base += "$type"
		}
		bases[def.Name] = base
		counts[base]++
	}

	names := make(map[typegrammar.Name]string, len(defs))
	for _, def := range defs {
		base := bases[def.Name]
		if counts[base] > 1 {
			identity := def.Name.PackagePath + "\x00" + def.Name.Name
			base += "$" + hex.EncodeToString([]byte(identity))
		}
		names[def.Name] = base
	}
	return names
}

func safeIdentifier(name string) string {
	var out strings.Builder
	for i, r := range name {
		if r == '_' || r < utf8.RuneSelf && (unicode.IsLetter(r) || i > 0 && unicode.IsDigit(r)) {
			out.WriteRune(r)
			continue
		}
		if r >= utf8.RuneSelf && (unicode.IsLetter(r) || i > 0 && unicode.IsDigit(r)) {
			fmt.Fprintf(&out, "_u%X_", r)
			continue
		}
		fmt.Fprintf(&out, "_u%X_", r)
	}
	return out.String()
}

